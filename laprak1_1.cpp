#include <iostream>

using namespace std;

int main() {    
    float bill1, bill2;

    cout << "Masukkan bilangan 1 : ";
    cin >> bill1;

    cout <<"Masukkan bilangan 2 : ";
    cin >> bill2;


    cout <<"Hasil penjumlahan dari : " << bill1 + bill2 << endl;
    cout <<"Hasil pengurangan dari : " << bill1 - bill2 << endl;
    cout <<"Hasil perkalian dari : " << bill1 * bill2 << endl;
    cout <<"Hasil pembagian dari : " << bill1 / bill2 << endl;
    return 0;
}
